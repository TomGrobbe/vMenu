using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace vMenu.Enhanced.Localization.Generator;

/// <summary>Writes the English table from the [English] attributes on the Loc constants, so each key's English sits
/// next to it and a key without English does not compile.</summary>
[Generator(LanguageNames.CSharp)]
public sealed class EnglishStringsGenerator : IIncrementalGenerator
{
    private const string LocType = "vMenu.Enhanced.Localization.Loc";
    private const string AttributeType = "vMenu.Enhanced.Localization.EnglishAttribute";
    private const string DescriptionSuffix = ".desc";

    private static readonly DiagnosticDescriptor MissingEnglish = new(
        "VMENULOC001",
        "Translation key without English",
        "Loc.{0} has no [English(...)] text. Every key needs one, English is the fallback for every other language.",
        "Localization",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor DuplicateKey = new(
        "VMENULOC002",
        "Translation key defined twice",
        "The key '{0}' comes from both {1} and {2}. Keep one of them.",
        "Localization",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context) =>
        context.RegisterSourceOutput(context.CompilationProvider, static (spc, compilation) => Emit(spc, compilation));

    /// <summary>A duplicated key is reported, then left out rather than failing the whole table, so that error is the
    /// only one the build shows.</summary>
    private static void Emit(SourceProductionContext context, Compilation compilation)
    {
        var loc = compilation.GetTypeByMetadataName(LocType);
        var attribute = compilation.GetTypeByMetadataName(AttributeType);

        if (loc is null || attribute is null)
        {
            return;
        }

        var entries = new List<Entry>();

        Collect(context, loc, string.Empty, attribute, entries);

        var seen = new Dictionary<string, Entry>(StringComparer.Ordinal);
        var kept = new List<Entry>();

        foreach (var entry in entries)
        {
            if (seen.TryGetValue(entry.Key, out var first))
            {
                context.ReportDiagnostic(Diagnostic.Create(DuplicateKey, entry.Location, entry.Key, first.Source, entry.Source));

                continue;
            }

            seen.Add(entry.Key, entry);
            kept.Add(entry);
        }

        context.AddSource("EnglishStrings.g.cs", SourceText.From(Render(kept), Encoding.UTF8));
    }

    private static void Collect(SourceProductionContext context, INamedTypeSymbol type, string path, INamedTypeSymbol attribute, List<Entry> entries)
    {
        foreach (var field in type.GetMembers().OfType<IFieldSymbol>())
        {
            if (!field.IsConst || field.ConstantValue is not string key)
            {
                continue;
            }

            var name = path + field.Name;
            var location = field.Locations.FirstOrDefault();
            var english = field.GetAttributes()
                .FirstOrDefault(data => SymbolEqualityComparer.Default.Equals(data.AttributeClass, attribute));

            if (english is null || english.ConstructorArguments.Length == 0 || english.ConstructorArguments[0].Value is not string text)
            {
                context.ReportDiagnostic(Diagnostic.Create(MissingEnglish, location, name));

                continue;
            }

            entries.Add(new Entry(key, $"Loc.{name}", $"global::{LocType}.{name}", text, location));

            if (english.ConstructorArguments.Length > 1 && english.ConstructorArguments[1].Value is string description)
            {
                entries.Add(new Entry(
                    key + DescriptionSuffix,
                    $"the description on Loc.{name}",
                    $"global::{LocType}.{name} + \"{DescriptionSuffix}\"",
                    description,
                    location));
            }
        }

        foreach (var nested in type.GetTypeMembers())
        {
            Collect(context, nested, $"{path}{nested.Name}.", attribute, entries);
        }
    }

    private static string Render(List<Entry> entries)
    {
        var builder = new StringBuilder();

        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("namespace vMenu.Enhanced.Localization.Languages;");
        builder.AppendLine();
        builder.AppendLine("/// <summary>The English strings, and the fallback for every other language. Written by the build from the");
        builder.AppendLine("/// [English] attributes on the Loc constants. Other languages live in JSON under");
        builder.AppendLine("/// <c>assets/shared/language/</c>, so update those too when you change a string.</summary>");
        builder.AppendLine("internal static class EnglishStrings");
        builder.AppendLine("{");
        builder.AppendLine("    internal static LanguageTable Table { get; } = new(");
        builder.AppendLine("        LanguageId.English,");
        builder.AppendLine("        \"English\",");
        builder.AppendLine("        new global::System.Collections.Generic.Dictionary<string, string>(global::System.StringComparer.Ordinal)");
        builder.AppendLine("        {");

        foreach (var entry in entries)
        {
            builder.Append("            [").Append(entry.Expression).Append("] = ")
                .Append(SymbolDisplay.FormatLiteral(entry.Text, quote: true)).AppendLine(",");
        }

        builder.AppendLine("        });");
        builder.AppendLine("}");

        return builder.ToString();
    }

    private sealed class Entry(string key, string source, string expression, string text, Location? location)
    {
        public string Key { get; } = key;

        public string Source { get; } = source;

        public string Expression { get; } = expression;

        public string Text { get; } = text;

        public Location? Location { get; } = location;
    }
}
